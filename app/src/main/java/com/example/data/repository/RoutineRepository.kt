package com.example.data.repository

import com.example.data.db.RoutineDao
import com.example.data.db.RoutineEntity
import com.example.data.model.ClassRoutine
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.map

class RoutineRepository(
  private val routineDao: RoutineDao
) {
  val allRoutines: Flow<List<ClassRoutine>> = routineDao.getAllRoutines().map { list ->
    list.map { it.toClassRoutine() }
  }

  suspend fun insertRoutine(routine: ClassRoutine) {
    routineDao.insertRoutine(RoutineEntity.fromClassRoutine(routine))
  }

  suspend fun insertAll(routines: List<ClassRoutine>) {
    routineDao.insertAll(routines.map { RoutineEntity.fromClassRoutine(it) })
  }

  suspend fun updateRoutine(routine: ClassRoutine) {
    routineDao.updateRoutine(RoutineEntity.fromClassRoutine(routine))
  }

  suspend fun deleteRoutine(id: String) {
    routineDao.deleteById(id)
  }

  suspend fun deleteAll() {
    routineDao.deleteAll()
  }

  fun exportScheduleAsText(routines: List<ClassRoutine>): String {
    val days = listOf("Monday", "Tuesday", "Wednesday", "Thursday", "Friday", "Saturday", "Sunday")
    val sb = StringBuilder()
    sb.appendLine("🎓 UNIVERSITY CLASS ROUTINE")
    sb.appendLine("==========================================")
    sb.appendLine("Generated by UniRoutine Class Scheduler")
    sb.appendLine()

    for (day in days) {
      val dayRoutines = routines.filter { it.dayOfWeek.equals(day, ignoreCase = true) }
        .sortedBy { it.startMinutes }
      if (dayRoutines.isNotEmpty()) {
        sb.appendLine("📅 $day (${dayRoutines.size} classes)")
        sb.appendLine("------------------------------------------")
        for (item in dayRoutines) {
          sb.appendLine("  • ${item.startTime} - ${item.endTime} | ${item.courseCode} - ${item.courseTitle}")
          val details = mutableListOf<String>()
          if (item.room.isNotBlank()) details.add("Room: ${item.room}")
          if (item.instructor.isNotBlank()) details.add("Instructor: ${item.instructor}")
          if (item.section.isNotBlank()) details.add("Sec: ${item.section}")
          if (details.isNotEmpty()) {
            sb.appendLine("    ${details.joinToString(" • ")}")
          }
          if (item.notes.isNotBlank()) {
            sb.appendLine("    Note: ${item.notes}")
          }
          sb.appendLine()
        }
      }
    }
    return sb.toString()
  }

  fun exportAsIcs(routines: List<ClassRoutine>): String {
    val sb = StringBuilder()
    sb.appendLine("BEGIN:VCALENDAR")
    sb.appendLine("VERSION:2.0")
    sb.appendLine("PRODID:-//UniRoutine//Class Scheduler//EN")
    sb.appendLine("CALSCALE:GREGORIAN")

    val dayToRrule = mapOf(
      "Monday" to "MO",
      "Tuesday" to "TU",
      "Wednesday" to "WE",
      "Thursday" to "TH",
      "Friday" to "FR",
      "Saturday" to "SA",
      "Sunday" to "SU"
    )

    for (item in routines) {
      val rruleDay = dayToRrule[item.dayOfWeek] ?: "MO"
      sb.appendLine("BEGIN:VEVENT")
      sb.appendLine("SUMMARY:${item.courseCode} - ${item.courseTitle}")
      sb.appendLine("LOCATION:${item.room}")
      sb.appendLine("DESCRIPTION:Instructor: ${item.instructor}\\nSection: ${item.section}\\nNotes: ${item.notes}")
      sb.appendLine("RRULE:FREQ=WEEKLY;BYDAY=$rruleDay")
      sb.appendLine("END:VEVENT")
    }
    sb.appendLine("END:VCALENDAR")
    return sb.toString()
  }
}
